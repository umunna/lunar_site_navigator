//
// Validation records: each V-test writes data/validation/<ID>.json. The report
// generator renders docs/VALIDATION.md from whatever records exist. A test
// that has no record is printed as "not run" and must not be quoted as a result.
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { DATA_DIR, DOCS_DIR } from '../paths';

export const VALIDATION_DIR = join(DATA_DIR, 'validation');

export interface ValidationRecord {
  readonly id: string;
  readonly title: string;
  readonly criterion: string;
  readonly status: 'pass' | 'fail';
  readonly generatedAtUtc: string;
  /** One-line result, safe to show on the About page. */
  readonly summary: string;
  /** Markdown lines with the detail (tables, notes, deviations). */
  readonly details: readonly string[];
}

/** The planned checks, in order. The titles are shown on the app's About page, so they use plain words. */
export const PLANNED_TESTS: readonly { id: string; title: string; criterion: string }[] = [
  { id: 'V0', title: 'The Moon height map is the right way round', criterion: 'Known craters are low, Mons Malapert is high, and only one orientation of the map fits' },
  { id: 'V1', title: 'Our Sun and Earth directions agree with NASA JPL Horizons', criterion: 'Sun within 0.001 degrees and Earth within 0.01 degrees, at 8 places and 300 times each, from the file that the app uses' },
  { id: 'V2', title: 'The horizon calculation is correct on test shapes', criterion: 'Agreement with exact formulas, correct compass direction, correct result after a rotation and after halving the step' },
  { id: 'V3', title: 'Sunlight at 3 places compared with NASA\'s published light map', criterion: 'The difference at each place is reported. An exact match is not expected: the time span, the map detail and the observer height differ' },
  { id: 'V4', title: 'Countdowns and totals are correct', criterion: 'Agreement with a slow, simple count for the time to sunset and Earthset and for the totals of a stay' },
];

/** Title and pass criterion of a planned check. One definition, so a record never drifts from the list. */
export function plannedCheck(id: string): { id: string; title: string; criterion: string } {
  const t = PLANNED_TESTS.find((p) => p.id === id);
  if (t === undefined) {
    throw new Error(`no planned check with the id ${id}`);
  }
  return t;
}

export async function saveRecord(record: ValidationRecord): Promise<string> {
  await mkdir(VALIDATION_DIR, { recursive: true });
  const path = join(VALIDATION_DIR, `${record.id}.json`);
  await writeFile(path, `${JSON.stringify(record, null, 2)}\n`, 'utf8');
  return path;
}

/** A validation record file is `<ID>.json`. The generated `index.json` lives beside them and is not one. */
export function isRecordFile(name: string): boolean {
  return /^V\d+\.json$/.test(name);
}

export async function loadRecords(): Promise<ValidationRecord[]> {
  let names: string[] = [];
  try {
    names = await readdir(VALIDATION_DIR);
  } catch {
    return [];
  }
  const records: ValidationRecord[] = [];
  for (const name of names.filter(isRecordFile).sort()) {
    records.push(JSON.parse(await readFile(join(VALIDATION_DIR, name), 'utf8')) as ValidationRecord);
  }
  return records;
}

export function renderReport(records: readonly ValidationRecord[]): string {
  const byId = new Map(records.map((r) => [r.id, r]));
  const lines: string[] = [
    '# Validation report',
    '',
    'This file is generated by `packages/pipeline`. Do not edit it by hand. The README tells you how to run the checks.',
    'A check with the status "not run" has no result. We make no claim for it.',
    '',
    '| ID | Check | Pass criterion | Status |',
    '|---|---|---|---|',
  ];
  for (const t of PLANNED_TESTS) {
    const r = byId.get(t.id);
    lines.push(`| ${t.id} | ${t.title} | ${t.criterion} | ${r === undefined ? 'not run' : r.status.toUpperCase()} |`);
  }
  for (const r of records) {
    lines.push('', `## ${r.id}: ${r.title}`, '', `Status: **${r.status.toUpperCase()}** (generated ${r.generatedAtUtc})`, '', r.summary, '', ...r.details);
  }
  return `${lines.join('\n')}\n`;
}

/** Compact index for the app's About page: every planned test with its status and one-line result. */
export function renderIndex(records: readonly ValidationRecord[]): string {
  const byId = new Map(records.map((r) => [r.id, r]));
  const entries = PLANNED_TESTS.map((t) => {
    const r = byId.get(t.id);
    return {
      id: t.id,
      title: t.title,
      criterion: t.criterion,
      status: r === undefined ? 'not run' : r.status,
      summary: r === undefined ? '' : r.summary,
    };
  });
  return `${JSON.stringify(entries, null, 2)}\n`;
}

export async function writeReport(): Promise<string> {
  const records = await loadRecords();
  const path = join(DOCS_DIR, 'VALIDATION.md');
  await mkdir(DOCS_DIR, { recursive: true });
  await writeFile(path, renderReport(records), 'utf8');
  await mkdir(VALIDATION_DIR, { recursive: true });
  await writeFile(join(VALIDATION_DIR, 'index.json'), renderIndex(records), 'utf8');
  return path;
}
